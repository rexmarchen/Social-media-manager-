console = Console()


def create_training_zip(clean_dir: Path, zip_output_path: Path) -> Path:
    """Zips all paired .jpg and .txt training files into a single training kit archive."""
    clean_dir = Path(clean_dir)
    zip_output_path = Path(zip_output_path)
    zip_output_path.parent.mkdir(parents=True, exist_ok=True)

    files_to_zip = [
        p for p in clean_dir.iterdir()
        if p.suffix.lower() in (".jpg", ".jpeg", ".png", ".txt") and p.is_file()
    ]

    if not files_to_zip:
        raise ValueError(f"No training images or captions found in {clean_dir}.")

    with zipfile.ZipFile(zip_output_path, "w", zipfile.ZIP_DEFLATED) as zf:
        for f in files_to_zip:
            zf.write(f, arcname=f.name)

    size_mb = os.path.getsize(zip_output_path) / (1024 * 1024)
    console.print(f"[green]Zipped {len(files_to_zip)} training files into {zip_output_path} ({size_mb:.2f} MB)[/green]")
    return zip_output_path


