def export_training_kit_bundle(
    clean_dir: Path = Path("dataset/clean"),
    output_zip: Path = Path("outputs/training_kit.zip"),
    notebook_dir: Path = Path("notebooks"),
    guide_path: Path = Path("TRAINING_GUIDE.md"),
    trigger_word: str = "rexstyle",
    resolution: int = 1024,
    rank: int = 16,
    steps: int = 1200,
    save_every: int = 250,
) -> Dict[str, Path]:
    """Orchestrates packaging of dataset, notebook generation, and guide creation."""
    console.print("[bold cyan]Exporting Free LoRA Training Kit...[/bold cyan]")

    # 1. Zip dataset
    zip_path = create_training_zip(clean_dir, output_zip)

    # 2. Generate Colab Notebook
    notebook_dir = Path(notebook_dir)
    notebook_dir.mkdir(parents=True, exist_ok=True)
    nb_file = notebook_dir / "train_sdxl_lora_colab.ipynb"
    nb_content = generate_colab_notebook_content(
        trigger_word=trigger_word,
        resolution=resolution,
        rank=rank,
        steps=steps,
        save_every_n_steps=save_every,
    )
    with open(nb_file, "w", encoding="utf-8") as f:
        json.dump(nb_content, f, indent=2)
    console.print(f"[bold green]Saved Colab Notebook to {nb_file}[/bold green]")

    # 3. Generate Training Guide
    generate_training_guide(guide_path)

    return {
        "zip": zip_path,
        "notebook": nb_file,
        "guide": guide_path,
    }
